export async function listGoogleCalendarEvents(token: string): Promise<GoogleCalendarEvent[]> {
  const now = new Date().toISOString();
  const url = `https://www.googleapis.com/calendar/v3/calendars/primary/events?timeMin=${encodeURIComponent(now)}&maxResults=25&singleEvents=true&orderBy=startTime`;

  const res = await fetch(url, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  });

  if (!res.ok) {
    const err = await res.text();
    throw new Error(`Calendar list failed: ${res.status} ${err}`);
  }

  const data = await res.json();
  return data.items || [];
}

export async function createGoogleCalendarPublishingEvent(
  token: string,
  item: ContentCalendarItem
): Promise<GoogleCalendarEvent> {
  const dateStr = item.scheduledDate;
  const timeStr = item.scheduledTime || '09:00';
  const startIso = `${dateStr}T${timeStr}:00`;

  // Duration 30 mins
  const startDate = new Date(startIso);
  const endDate = new Date(startDate.getTime() + 30 * 60000);

  const payload = {
    summary: `[AEObility Social] Dispatch ${item.channel.toUpperCase()}: ${item.title.slice(0, 40)}`,
    description: `Automated Social Media Engine Publishing Slot\n\nChannel: ${item.channel.toUpperCase()}\nStatus: ${item.status}\nGatekeeper Score: ${item.gatekeeperScore}%\nHook:\n${item.hook}\n\nFull Copy:\n${item.copy}\n\nCreative Asset: ${item.creativeAssetLink || 'None'}\nCanonical Ref: ${item.iaNodeId}`,
    start: {
      dateTime: startDate.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    },
    end: {
      dateTime: endDate.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    },
    reminders: {
      useDefault: false,
      overrides: [
        { method: 'popup', minutes: 15 },
        { method: 'email', minutes: 60 },
      ],
    },
  };

  const res = await fetch('https://www.googleapis.com/calendar/v3/calendars/primary/events', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(payload),
  });

  if (!res.ok) {
    const err = await res.text();
    throw new Error(`Failed to schedule Calendar event: ${res.status} ${err}`);
  }

  return await res.json();
}
