export async function listDriveFiles(token: string, folderId: string = TARGET_DRIVE_FOLDER_ID): Promise<DriveItem[]> {
  // Query both files in folder and user files
  const query = folderId
    ? `'${folderId}' in parents and trashed = false`
    : 'trashed = false';

  const url = `https://www.googleapis.com/drive/v3/files?pageSize=25&fields=files(id,name,mimeType,modifiedTime,webViewLink)&q=${encodeURIComponent(
    query
  )}`;

  let res = await fetch(url, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  });

  // Fallback to general files query if specific folder has permission nuances
  if (!res.ok && folderId) {
    const fallbackUrl = 'https://www.googleapis.com/drive/v3/files?pageSize=25&fields=files(id,name,mimeType,modifiedTime,webViewLink)&q=trashed = false';
    res = await fetch(fallbackUrl, {
      headers: {
        Authorization: `Bearer ${token}`,
      },
    });
  }

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Google Drive API error: ${res.status} ${errorText}`);
  }

  const data = await res.json();
  return data.files || [];
}

export async function readDriveDocumentContent(token: string, fileId: string, mimeType: string): Promise<string> {
  let url = `https://www.googleapis.com/drive/v3/files/${fileId}?alt=media`;
  if (mimeType === 'application/vnd.google-apps.document') {
    url = `https://www.googleapis.com/drive/v3/files/${fileId}/export?mimeType=text/plain`;
  }

  const res = await fetch(url, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  });

  if (!res.ok) {
    throw new Error(`Failed to read Drive document: ${res.status}`);
  }

  return await res.text();
}

export async function uploadGraphicToDrive(
  token: string,
  base64PngDataUrl: string,
  fileName: string,
  folderId: string = TARGET_DRIVE_FOLDER_ID
): Promise<{ id: string; webViewLink?: string }> {
  // Convert Data URL to binary blob
  const base64Data = base64PngDataUrl.split(',')[1];
  const binaryString = atob(base64Data);
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  const blob = new Blob([bytes], { type: 'image/png' });

  const metadata: Record<string, unknown> = {
    name: fileName,
    mimeType: 'image/png',
    description: 'Generated by AEObility Autonomous Social Engine',
  };

  if (folderId) {
    metadata.parents = [folderId];
  }

  const form = new FormData();
  form.append('metadata', new Blob([JSON.stringify(metadata)], { type: 'application/json' }));
  form.append('file', blob);

  const res = await fetch('https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
    },
    body: form,
  });

  if (!res.ok) {
    const err = await res.text();
    throw new Error(`Drive upload failed: ${res.status} ${err}`);
  }

  return await res.json();
}

